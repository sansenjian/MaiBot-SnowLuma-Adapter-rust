/// face 段的文本化：emoji 近似优先，其次 [描述]，兜底 [表情]。
pub fn face_text(id: &str) -> String {
    if let Some(e) = emoji(id) {
        return e.to_owned();
    }
    if let Some(d) = description(id) {
        return format!("[{d}]");
    }
    "[表情]".to_owned()
}

